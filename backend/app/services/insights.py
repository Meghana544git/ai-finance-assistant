"""Rule-based, data-backed financial insights.

Every insight is computed from the authenticated user's saved transactions and
budgets. These are deterministic rules, not ML predictions, and the API labels
them as ``source: rule_based``. ML output is surfaced separately by
``/api/ml/predict-spending``.
"""

from __future__ import annotations

from datetime import date

from sqlalchemy.orm import Session

from app.services.analytics import (
    MONTH_NAMES,
    budgets_for_period,
    category_breakdown,
    expenses_for_period,
    income_for_period,
    shift_month,
    total_balance,
    transaction_count_for_period,
)
from app.services.formatting import format_money

DISCLAIMER = (
    "Insights are generated by transparent rules from your own records. "
    "They are educational and not professional financial advice."
)


def _change(current: float, previous: float) -> float | None:
    if previous <= 0:
        return None
    return round(((current - previous) / previous) * 100, 1)


def build_insights(db: Session, user_id: int, year: int, month: int, currency: str = "INR") -> dict:
    prev_year, prev_month = shift_month(year, month, -1)
    income = income_for_period(db, user_id, year, month)
    expenses = expenses_for_period(db, user_id, year, month)
    prev_expenses = expenses_for_period(db, user_id, prev_year, prev_month)
    prev_income = income_for_period(db, user_id, prev_year, prev_month)
    count = transaction_count_for_period(db, user_id, year, month)
    total_exp, categories = category_breakdown(db, user_id, year, month)
    budgets = budgets_for_period(db, user_id, year, month)

    insights: list[dict] = []
    period = f"{MONTH_NAMES[month - 1]} {year}"

    if count == 0:
        insights.append(
            {
                "insight_type": "getting_started",
                "title": "Start by recording a transaction",
                "description": (
                    f"There are no transactions recorded for {period} yet. Add your income "
                    "and a few expenses to unlock spending analysis, budget tracking and "
                    "personalised insights."
                ),
                "severity": "info",
            }
        )
        return {
            "insights": insights,
            "month": month,
            "year": year,
            "currency": currency,
            "data_points": 0,
        }

    # 1. Highest spending category -----------------------------------------
    if categories:
        top = categories[0]
        insights.append(
            {
                "insight_type": "top_category",
                "title": f"{top['category']} is your highest spending category",
                "description": (
                    f"You spent {format_money(top['amount'], currency)} on {top['category']} "
                    f"in {period}, which is {top['percentage']:.1f}% of your total expenses "
                    f"across {top['transaction_count']} transaction(s)."
                ),
                "severity": "info",
            }
        )

        # 2. Actionable reduction suggestion (10% rule) --------------------
        saving = round(float(top["amount"]) * 0.10, 2)
        insights.append(
            {
                "insight_type": "suggestion",
                "title": f"Try trimming {top['category']} by 10%",
                "description": (
                    f"Reducing {top['category']} spending by 10% next month would free up "
                    f"about {format_money(saving, currency)}. Set a category budget to track it."
                ),
                "severity": "suggestion",
            }
        )
    else:
        insights.append(
            {
                "insight_type": "no_expenses",
                "title": "No expenses recorded this month",
                "description": (
                    f"Income of {format_money(income, currency)} is recorded for {period}, "
                    "but no expenses yet. Add expenses to see category analysis."
                ),
                "severity": "info",
            }
        )

    # 3. Month-over-month spending change ----------------------------------
    change = _change(expenses, prev_expenses)
    if change is not None:
        if change > 10:
            insights.append(
                {
                    "insight_type": "spending_increase",
                    "title": f"Spending is up {change:.1f}% from last month",
                    "description": (
                        f"Expenses rose from {format_money(prev_expenses, currency)} in "
                        f"{MONTH_NAMES[prev_month - 1]} to {format_money(expenses, currency)} "
                        f"in {period}. Review the category breakdown to find the driver."
                    ),
                    "severity": "warning",
                }
            )
        elif change < -10:
            insights.append(
                {
                    "insight_type": "spending_decrease",
                    "title": f"Spending is down {abs(change):.1f}% from last month",
                    "description": (
                        f"Expenses fell from {format_money(prev_expenses, currency)} to "
                        f"{format_money(expenses, currency)}. That is a "
                        f"{format_money(max(prev_expenses - expenses, 0), currency)} improvement."
                    ),
                    "severity": "positive",
                }
            )
        else:
            insights.append(
                {
                    "insight_type": "spending_stable",
                    "title": "Spending is broadly stable",
                    "description": (
                        f"Expenses of {format_money(expenses, currency)} are within 10% of "
                        f"last month ({format_money(prev_expenses, currency)})."
                    ),
                    "severity": "positive",
                }
            )

    # 4. Budget warnings ---------------------------------------------------
    for entry in budgets:
        budget = entry["budget"]
        label = budget.category or "Overall"
        if entry["status"] == "exceeded":
            insights.append(
                {
                    "insight_type": "budget_exceeded",
                    "title": f"{label} budget exceeded",
                    "description": (
                        f"You have spent {format_money(entry['spent'], currency)} of your "
                        f"{format_money(float(budget.monthly_limit), currency)} {label.lower()} "
                        f"budget ({entry['utilization']:.1f}%), exceeding it by "
                        f"{format_money(abs(entry['remaining']), currency)}."
                    ),
                    "severity": "critical",
                }
            )
        elif entry["status"] == "warning":
            insights.append(
                {
                    "insight_type": "budget_warning",
                    "title": f"{label} budget at {entry['utilization']:.1f}%",
                    "description": (
                        f"You have {format_money(entry['remaining'], currency)} left in your "
                        f"{label.lower()} budget. Slow down to stay within the monthly limit."
                    ),
                    "severity": "warning",
                }
            )

    # 5. Savings analysis --------------------------------------------------
    if income > 0:
        savings = round(income - expenses, 2)
        savings_rate = round((savings / income) * 100, 1)
        if savings < 0:
            insights.append(
                {
                    "insight_type": "negative_savings",
                    "title": "You are spending more than you earn this month",
                    "description": (
                        f"Income is {format_money(income, currency)} but expenses are "
                        f"{format_money(expenses, currency)}, a shortfall of "
                        f"{format_money(abs(savings), currency)}. Consider pausing non-essential "
                        "spending for the rest of the month."
                    ),
                    "severity": "critical",
                }
            )
        else:
            previous_rate = (
                round(((prev_income - prev_expenses) / prev_income) * 100, 1) if prev_income > 0 else None
            )
            trend = ""
            if previous_rate is not None:
                delta = round(savings_rate - previous_rate, 1)
                if delta >= 1:
                    trend = f" That is {delta:.1f} percentage points higher than last month."
                elif delta <= -1:
                    trend = f" That is {abs(delta):.1f} percentage points lower than last month."
            insights.append(
                {
                    "insight_type": "savings_rate",
                    "title": f"Your savings rate is {savings_rate:.1f}%",
                    "description": (
                        f"You saved {format_money(savings, currency)} from "
                        f"{format_money(income, currency)} of income this month.{trend}"
                    ),
                    "severity": "positive" if savings_rate >= 20 else "info",
                }
            )
    else:
        insights.append(
            {
                "insight_type": "no_income",
                "title": "No income recorded this month",
                "description": (
                    "Add your salary or other income to calculate a savings rate and compare "
                    "income with expenses."
                ),
                "severity": "info",
            }
        )

    # 6. Overall balance ---------------------------------------------------
    balance = total_balance(db, user_id)
    insights.append(
        {
            "insight_type": "balance",
            "title": "Your recorded balance",
            "description": (
                f"Across all recorded transactions, income minus expenses equals "
                f"{format_money(balance, currency)}. This is not a bank balance - only what "
                "you have entered in this app."
            ),
            "severity": "info",
        }
    )

    return {
        "insights": insights,
        "month": month,
        "year": year,
        "currency": currency,
        "data_points": count,
    }
