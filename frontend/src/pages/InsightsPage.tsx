import { ArrowRight, BrainCircuit, RefreshCw, ShieldCheck, Sparkles } from "lucide-react";
import { useCallback, useEffect, useState } from "react";
import { Link } from "react-router-dom";

import { EmptyState } from "@/components/EmptyState";
import { ErrorState } from "@/components/ErrorState";
import { MonthPicker } from "@/components/MonthPicker";
import { PageHeader } from "@/components/PageHeader";
import { SeverityIcon } from "@/components/InsightSeverity";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { useAuth } from "@/context/AuthContext";
import { getApiError } from "@/services/api";
import { insightService } from "@/services/insights.service";
import { mlService } from "@/services/ml.service";
import type { InsightsResponse, SpendingForecast } from "@/types";
import { formatCurrency, monthKeyToLabel } from "@/utils/format";

export function InsightsPage() {
  const { currency } = useAuth();
  const today = new Date();
  const [month, setMonth] = useState(today.getMonth() + 1);
  const [year, setYear] = useState(today.getFullYear());
  const [data, setData] = useState<InsightsResponse | null>(null);
  const [forecast, setForecast] = useState<SpendingForecast | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [reloadKey, setReloadKey] = useState(0);

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const [insightsData, forecastData] = await Promise.all([
        insightService.list(month, year),
        mlService.predictSpending().catch(() => null),
      ]);
      setData(insightsData);
      setForecast(forecastData);
    } catch (err) {
      setError(getApiError(err));
    } finally {
      setLoading(false);
    }
  }, [month, year]);

  useEffect(() => {
    void load();
  }, [load, reloadKey]);

  const refresh = () => setReloadKey((key) => key + 1);

  return (
    <div className="space-y-5">
      <PageHeader
        eyebrow="Rule-based analysis"
        title="AI Insights"
        description="Plain-English observations generated by transparent rules from your own records. Predictions live separately so the two are never confused."
        actions={
          <>
            <MonthPicker month={month} year={year} onChange={(m, y) => { setMonth(m); setYear(y); }} />
            <Button variant="outline" onClick={refresh} disabled={loading}>
              <RefreshCw className={`h-4 w-4 ${loading ? "animate-spin" : ""}`} /> Refresh
            </Button>
          </>
        }
      />

      <Card className="border-emerald-100 bg-gradient-to-br from-emerald-50/80 to-white">
        <CardContent className="flex flex-col gap-3 p-5 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex items-start gap-3">
            <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-emerald-600 text-white">
              <ShieldCheck className="h-5 w-5" />
            </div>
            <div>
              <p className="text-sm font-semibold text-navy-900">How these insights are produced</p>
              <p className="mt-1 max-w-2xl text-xs leading-relaxed text-slate-500">
                Deterministic rules compare your current month with the previous month, inspect
                budget utilisation and calculate savings from recorded income and expenses. No
                language model is involved and no numbers are invented.
              </p>
            </div>
          </div>
          <Badge variant="success" className="shrink-0 gap-1 self-start sm:self-auto">
            <Sparkles className="h-3 w-3" /> source: rule_based
          </Badge>
        </CardContent>
      </Card>

      {error ? (
        <ErrorState message={error} onRetry={load} />
      ) : loading ? (
        <div className="grid gap-4 lg:grid-cols-2">
          {Array.from({ length: 4 }).map((_, index) => (
            <Skeleton key={index} className="h-[136px] rounded-2xl" />
          ))}
        </div>
      ) : (
        <>
          <div className="flex flex-wrap items-center gap-2 text-xs text-slate-400">
            <span>
              Showing insights for{" "}
              <span className="font-semibold text-navy-900">
                {data ? `${new Date(data.year, data.month - 1, 1).toLocaleString("en-GB", { month: "long", year: "numeric" })}` : ""}
              </span>
            </span>
            <span>·</span>
            <span>{data?.data_points ?? 0} transaction(s) analysed</span>
          </div>

          {data && data.insights.length > 0 ? (
            <div className="grid gap-4 lg:grid-cols-2">
              {data.insights.map((insight, index) => (
                <Card key={`${insight.insight_type}-${index}`} className="transition-shadow hover:shadow-lift">
                  <CardContent className="flex items-start gap-3.5 p-5">
                    <SeverityIcon severity={insight.severity} />
                    <div className="min-w-0">
                      <div className="flex flex-wrap items-center gap-2">
                        <p className="text-sm font-bold text-navy-900">{insight.title}</p>
                        <Badge
                          variant={
                            insight.severity === "critical"
                              ? "danger"
                              : insight.severity === "warning"
                                ? "warning"
                                : insight.severity === "positive"
                                  ? "success"
                                  : insight.severity === "suggestion"
                                    ? "purple"
                                    : "info"
                          }
                          className="text-[9px] uppercase tracking-wide"
                        >
                          {insight.severity}
                        </Badge>
                      </div>
                      <p className="mt-1.5 text-xs leading-relaxed text-slate-500">{insight.description}</p>
                      <p className="mt-2.5 text-[10px] font-medium uppercase tracking-wide text-slate-300">
                        {insight.insight_type.replaceAll("_", " ")}
                      </p>
                    </div>
                  </CardContent>
                </Card>
              ))}
            </div>
          ) : (
            <Card>
              <CardContent className="p-6">
                <EmptyState
                  icon={Sparkles}
                  title="Nothing to analyse yet"
                  description="Add transactions for this month and personalised insights will appear automatically."
                  action={
                    <Button asChild>
                      <Link to="/transactions?add=1">Add a transaction</Link>
                    </Button>
                  }
                />
              </CardContent>
            </Card>
          )}

          {data && (
            <div className="rounded-2xl border border-border bg-white p-4 text-[11px] leading-relaxed text-slate-400">
              <span className="font-semibold text-slate-500">Disclaimer:</span> {data.disclaimer}
            </div>
          )}
        </>
      )}

      <Card className="overflow-hidden border-0 bg-navy-900 text-white">
        <div className="hero-grid">
          <CardHeader className="pb-2">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="flex items-center gap-2.5">
                <div className="flex h-9 w-9 items-center justify-center rounded-xl bg-white/10 text-sky-300">
                  <BrainCircuit className="h-4 w-4" />
                </div>
                <div>
                  <CardTitle className="text-white">ML prediction — kept separate on purpose</CardTitle>
                  <p className="mt-1 text-xs text-slate-400">
                    Linear Regression on your monthly expense history
                  </p>
                </div>
              </div>
              <Badge className="border border-sky-400/20 bg-sky-400/10 text-sky-300">source: ML</Badge>
            </div>
          </CardHeader>
          <CardContent className="pt-3">
            {forecast?.status === "ok" ? (
              <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
                <div>
                  <p className="text-[11px] font-semibold uppercase tracking-wide text-slate-400">
                    Estimated spend for {forecast.prediction_month ? monthKeyToLabel(forecast.prediction_month) : "next month"}
                  </p>
                  <p className="mt-1 text-3xl font-extrabold tracking-tight text-white">
                    {formatCurrency(forecast.predicted_amount, currency)}
                  </p>
                  <p className="mt-1 text-[11px] text-slate-400">
                    Likely range {formatCurrency(forecast.lower_bound, currency)} –{" "}
                    {formatCurrency(forecast.upper_bound, currency)} · based on {forecast.months_used} months
                  </p>
                </div>
                <Button asChild variant="outline" className="border-white/15 bg-white/5 text-white hover:bg-white/10 hover:text-white">
                  <Link to="/predictions">
                    Full forecast <ArrowRight className="h-3.5 w-3.5" />
                  </Link>
                </Button>
              </div>
            ) : (
              <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
                <div>
                  <p className="text-sm font-semibold text-white">Forecast locked</p>
                  <p className="mt-1 max-w-xl text-xs leading-relaxed text-slate-400">
                    {forecast?.message ??
                      "The forecasting endpoint is unavailable right now. Check that the backend is running."}
                  </p>
                </div>
                <Button asChild variant="outline" className="border-white/15 bg-white/5 text-white hover:bg-white/10 hover:text-white">
                  <Link to="/predictions">
                    Details <ArrowRight className="h-3.5 w-3.5" />
                  </Link>
                </Button>
              </div>
            )}
            <p className="mt-4 border-t border-white/10 pt-3 text-[10px] leading-relaxed text-slate-500">
              ML estimates are statistical projections, not guarantees, and are never mixed into
              the rule-based insight cards above.
            </p>
          </CardContent>
        </div>
      </Card>
    </div>
  );
}
